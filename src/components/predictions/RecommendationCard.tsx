// ============================================================
// File: src/components/predictions/RecommendationCard.tsx
// Purpose: Shows the list of actionable recommendations generated
//          by the AI model, each tagged with a priority level
// Logic:
//   - Purely presentational, renders backend-provided text as-is
//   - Each recommendation gets a small priority badge, reusing the
//     same Low/Moderate/High color tokens as StatusBadge so the
//     color language stays consistent across the whole app
//   - Uses the tertiary accent color for the card itself, so the
//     recommendations visually read as "actionable advice",
//     distinct from the neutral result/explanation cards above it
// ============================================================
import { Lightbulb } from "lucide-react";
import type { PredictionResult, RecommendationItem } from "@/types/prediction";

interface RecommendationCardProps {
    result: PredictionResult;
}

// Priority -> badge color classes, aligned with the emission-level palette
// HIGH reuses "high" red, MEDIUM reuses "moderate" amber, LOW reuses "low"
// green, INFO falls back to a neutral tertiary tint
const PRIORITY_STYLES: Record<RecommendationItem["priority"], string> = {
    HIGH: "bg-emission-high/10 text-emission-high",
    MEDIUM: "bg-emission-moderate/10 text-emission-moderate",
    LOW: "bg-emission-low/10 text-emission-low",
    INFO: "bg-tertiary-container/20 text-tertiary",
};

// Displays the actionable, prioritized recommendation list for this prediction
export function RecommendationCard({ result }: RecommendationCardProps) {
    return (
        <div className="rounded-md border border-tertiary-container/30 bg-tertiary-container/10 p-5">
            <div className="flex items-start gap-3">
                {/* Icon badge: tertiary accent color, distinct from the
                    primary/semantic colors used elsewhere, to visually
                    flag this card as "advice", not "data" */}
                <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-full bg-tertiary-container/20">
                    <Lightbulb className="h-5 w-5 text-tertiary" strokeWidth={2} />
                </div>

                <div className="flex-1">
                    <h3 className="font-display text-base font-semibold text-on-surface">
                        AI recommendations
                    </h3>

                    {/* Recommendation list, generated by the AI model and
                        returned as-is from the backend, each with its own
                        priority badge */}
                    <ul className="mt-2 space-y-2">
                        {result.recommendations.map((item, index) => (
                            <li key={index} className="flex items-start gap-2">
                                <span
                                    className={`shrink-0 rounded-full px-2 py-0.5 text-[11px] font-medium ${PRIORITY_STYLES[item.priority]}`}
                                >
                                    {item.priority}
                                </span>
                                <p className="text-sm text-on-surface-variant">{item.recommendation}</p>
                            </li>
                        ))}
                    </ul>
                </div>
            </div>
        </div>
    );
}